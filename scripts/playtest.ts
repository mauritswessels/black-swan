/**
 * Bot playtest: every strategy plays the same set of seeded games, and we compare scores.
 *
 *   npm run playtest            -> 500 games per strategy, writes BALANCE.md
 *   npm run playtest -- 100     -> quicker run with 100 games
 */
import { writeFileSync } from 'node:fs';
import { BOTS, type Bot } from '../src/sim/bots';
import { initialState, isFinished, playedQuarters, step } from '../src/sim/model';
import { Rng } from '../src/sim/rng';
import { termScore } from '../src/sim/scoring';
import { targetFor } from '../src/sim/targets';
import type { GameOverReason, TargetMode } from '../src/sim/types';

const GAMES = Number(process.argv[2] ?? 500);

interface Row {
  bot: Bot;
  scores: number[];
  gameOvers: Partial<Record<GameOverReason, number>>;
  inflMiss: number;
  unemployment: number;
  credibility: number;
  approval: number;
  rateMoves: number;
}

function play(bot: Bot, seed: number, mode: TargetMode) {
  let s = initialState({ seed, targetMode: mode });
  const botRng = new Rng(seed ^ 0x9e3779b9);
  while (!isFinished(s)) s = step(s, bot.decide(s, botRng));
  return s;
}

function run(mode: TargetMode): Row[] {
  const tgt = targetFor(mode);
  return BOTS.map((bot) => {
    const row: Row = { bot, scores: [], gameOvers: {}, inflMiss: 0, unemployment: 0, credibility: 0, approval: 0, rateMoves: 0 };
    for (let g = 1; g <= GAMES; g++) {
      const s = play(bot, g, mode);
      row.scores.push(termScore(s));
      if (s.gameOver) row.gameOvers[s.gameOver] = (row.gameOvers[s.gameOver] ?? 0) + 1;
      const qs = playedQuarters(s);
      row.inflMiss += qs.reduce((a, q) => a + Math.abs(q.headline - tgt.centre), 0) / qs.length / GAMES;
      row.unemployment += qs.reduce((a, q) => a + q.unemployment, 0) / qs.length / GAMES;
      const last = qs[qs.length - 1];
      row.credibility += last.credibility / GAMES;
      row.approval += last.approval / GAMES;
      row.rateMoves += qs.filter((q, k) => k > 0 && q.policyRate !== qs[k - 1].policyRate).length / GAMES;
    }
    return row;
  });
}

const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / xs.length;
const pct = (xs: number[], p: number) => [...xs].sort((a, b) => a - b)[Math.floor(p * (xs.length - 1))];

function table(rows: Row[]): string {
  const lines = [
    '| Strategy | Avg score | Worst 10% | Best 10% | Game overs | Avg inflation miss | Avg unemployment | End credibility | End approval | Rate changes per term |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ];
  const sorted = [...rows].sort((a, b) => mean(b.scores) - mean(a.scores));
  for (const r of sorted) {
    const go = Object.values(r.gameOvers).reduce((a, b) => a + (b ?? 0), 0);
    const goText = go === 0 ? '0%' : `${((100 * go) / GAMES).toFixed(1)}% (${Object.entries(r.gameOvers).map(([k, v]) => `${k} ${v}`).join(', ')})`;
    lines.push(
      `| ${r.bot.name} | **${mean(r.scores).toFixed(1)}** | ${pct(r.scores, 0.1).toFixed(1)} | ${pct(r.scores, 0.9).toFixed(1)} | ${goText} | ${r.inflMiss.toFixed(2)} pts | ${r.unemployment.toFixed(2)}% | ${r.credibility.toFixed(0)} | ${r.approval.toFixed(0)}% | ${r.rateMoves.toFixed(1)} |`,
    );
  }
  return lines.join('\n');
}

const range = run('range');
const point = run('point');

const md = `# Balance report

Generated by \`npm run playtest\`. Each strategy played the same ${GAMES} games (seeds 1 to ${GAMES}), 20 quarters each, so the comparison is fair.

**Score:** each quarter earns 100 * e^(-loss / 3) points, and the term score is the average over 20 quarters. Quarters lost to a game over earn 0.
"Avg inflation miss" is the average distance of headline inflation from the centre of the target.

## Target: 0 to 2% range (default)

${table(range)}

## Target: 2% point

${table(point)}

## Strategies

${BOTS.map((b) => `- **${b.name}:** ${b.description}.`).join('\n')}
`;

writeFileSync('BALANCE.md', md);
console.log(md);
